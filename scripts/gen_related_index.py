#!/usr/bin/env python3
"""
Generate related-papers/index.html from the manifest related-papers/snapshot.tsv.

The collection began on 2026-03-22 with TeX sources and PDFs from
sibling research repositories and this repository's four papers.
Manifest dates identify the original entries. The page records later revisions.
snapshot.tsv has one row per TeX file (date, file, source, wave, title);
wave is "base", "last" or empty. The script checks that every listed .tex
exists, that every .tex in the directory is listed, and that the
dualsm_paper* copies equal papers/*/paper.tex and papers/*/paper.pdf.

Usage:
    python3 scripts/gen_related_index.py          # write index.html
    python3 scripts/gen_related_index.py --check  # exit 1 if index.html is stale
"""

import filecmp
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RELATED = os.path.join(ROOT, "related-papers")
MANIFEST = os.path.join(RELATED, "snapshot.tsv")
INDEX = os.path.join(RELATED, "index.html")

# dualsm copies and the paper directories they mirror
DUALSM_COPIES = {
    "dualsm_paper1_sp_duality": "paper-1-sp-duality-sm",
    "dualsm_paper2_meson_sum_rules": "paper-2-meson-mass-sum-rules",
    "dualsm_paper3_emergent_susy": "paper-3-emergent-susy-lattice",
    "dualsm_paper4_generation_number": "paper-4-generation-number",
}

FIELDS = ["date", "file", "source", "wave", "title"]

HEAD = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Related Papers</title>
<style>
  body { font-family: Georgia, serif; max-width: 1200px; margin: 2em auto; padding: 0 1em; background: #fafafa; color: #222; }
  h1 { border-bottom: 2px solid #444; padding-bottom: 0.3em; }
  p.meta { color: #666; font-size: 0.9em; }
  table { border-collapse: collapse; width: 100%; margin-top: 1.5em; font-size: 0.92em; }
  th { background: #3a5a8a; color: white; padding: 0.6em 0.8em; text-align: left; }
  tr:nth-child(even) { background: #eef2f7; }
  tr:hover { background: #d8e4f0; }
  td { padding: 0.5em 0.8em; vertical-align: top; border-bottom: 1px solid #ccc; }
  td.date { white-space: nowrap; font-family: monospace; color: #555; }
  td.src { font-family: monospace; font-size: 0.85em; color: #666; white-space: nowrap; }
  td.pdf { white-space: nowrap; text-align: center; }
  td.pdf a { display: inline-block; background: #c0392b; color: white; padding: 0.15em 0.5em; border-radius: 3px; font-size: 0.82em; font-family: sans-serif; }
  td.pdf a:hover { background: #962d22; text-decoration: none; }
  a { color: #1a5a8a; text-decoration: none; }
  a:hover { text-decoration: underline; }
  .wave-badge { display: inline-block; font-size: 0.75em; padding: 0.1em 0.4em; border-radius: 3px; margin-left: 0.4em; vertical-align: middle; }
  .base { background: #d4edda; color: #155724; }
  .last { background: #fff3cd; color: #856404; }
</style>
</head>
<body>
<h1>Related Papers</h1>
"""

META = """<p class="meta">This collection began on 2026-03-22 and holds {n_tex} TeX
sources and {n_pdf} compiled PDFs, ordered by their original file dates.
The {n_dualsm} DualSM papers track their sources in this repository.
The last version of <em>A Tale of Two Tuples</em> includes the 24 November
<a href="https://github.com/arivero/physres2/blob/6027cdc/sbootstrap_v4d.tex">Goldstino correction</a>.
The March versions of <em>From mesinos and quarkinos to the Standard Model</em>
retain the earlier inference. The <a href="https://github.com/arivero/dualsm/blob/master/papers/COMPOSITE-FLAVOUR-MATCHING.md#a-correction-to-the-parallel-oraifeartaigh-example">vacuum calculation</a>
explains why a smooth flavour deformation remains possible.<br>
For waved papers (multiple numbered versions sharing a base name), only the unnumbered base
and the last version are included.<br>
Generated by <code>scripts/gen_related_index.py</code> from <code>snapshot.tsv</code>.</p>
"""


def read_rows():
    rows = []
    with open(MANIFEST, encoding="utf-8") as fh:
        header = fh.readline().rstrip("\n").split("\t")
        if header != FIELDS:
            raise SystemExit(f"ERROR: snapshot.tsv header must be {FIELDS}")
        for n, line in enumerate(fh, start=2):
            if not line.strip():
                continue
            cells = line.rstrip("\n").split("\t")
            if len(cells) != len(FIELDS) or not re.match(r"\d{4}-\d{2}-\d{2}$", cells[0]) \
                    or not cells[1].endswith(".tex") or cells[3] not in ("", "base", "last"):
                raise SystemExit(f"ERROR: snapshot.tsv line {n} is malformed")
            date, fname, source, wave, title = cells
            rows.append((date, fname, title, source, wave or None))
    return rows


def problems_with(rows):
    problems = []
    listed = {r[1] for r in rows}
    on_disk = {f for f in os.listdir(RELATED) if f.endswith(".tex")}
    for f in sorted(on_disk - listed):
        problems.append(f"{f} is in related-papers/ but not in snapshot.tsv")
    for f in sorted(listed - on_disk):
        problems.append(f"{f} is listed in snapshot.tsv but missing")
    for stem, paper_dir in DUALSM_COPIES.items():
        for src, dst in ((f"papers/{paper_dir}/paper.tex", f"related-papers/{stem}.tex"),
                         (f"papers/{paper_dir}/paper.pdf", f"related-papers/pdf/{stem}.pdf")):
            a, b = os.path.join(ROOT, src), os.path.join(ROOT, dst)
            if not (os.path.exists(a) and os.path.exists(b)
                    and filecmp.cmp(a, b, shallow=False)):
                problems.append(f"{dst} differs from {src}")
    return problems


def render(rows):
    n_pdf = sum(os.path.exists(os.path.join(RELATED, "pdf", r[1][:-4] + ".pdf"))
                for r in rows)
    n_dualsm = sum(r[1].startswith("dualsm_") for r in rows)
    out = [HEAD, META.format(n_tex=len(rows), n_pdf=n_pdf, n_dualsm=n_dualsm),
           "\n<table>\n<thead>\n<tr>\n  <th>Date</th>\n  <th>File</th>\n"
           "  <th>Title</th>\n  <th>Source</th>\n  <th>PDF</th>\n</tr>\n"
           "</thead>\n<tbody>\n"]
    for date, fname, title, source, wave in rows:
        pdf = fname[:-4] + ".pdf"
        badge = (f' <span class="wave-badge {wave}">{wave} wave</span>'
                 if wave else "")
        pdf_cell = (f'<a href="pdf/{pdf}">PDF</a>'
                    if os.path.exists(os.path.join(RELATED, "pdf", pdf)) else "&mdash;")
        out.append(
            "<tr>\n"
            f'  <td class="date">{date}</td>\n'
            f'  <td><a href="{fname}">{fname}</a>{badge}</td>\n'
            f"  <td>{html.escape(title, quote=False)}</td>\n"
            f'  <td class="src">{source}</td>\n'
            f'  <td class="pdf">{pdf_cell}</td>\n'
            "</tr>\n")
    out.append("</tbody>\n</table>\n</body>\n</html>\n")
    return "".join(out)


def main():
    rows = read_rows()
    if not rows:
        print("ERROR: no rows found in related-papers/snapshot.tsv")
        return 1
    problems = problems_with(rows)
    for p in problems:
        print(f"ERROR: {p}")
    page = render(rows)
    if "--check" in sys.argv:
        with open(INDEX, encoding="utf-8") as fh:
            stale = fh.read() != page
        if stale:
            print("ERROR: related-papers/index.html is stale; "
                  "run scripts/gen_related_index.py")
        status = 1 if (stale or problems) else 0
        print(f"related-papers index: {len(rows)} entries, "
              f"{'OK' if status == 0 else 'FAIL'}")
        return status
    with open(INDEX, "w", encoding="utf-8") as fh:
        fh.write(page)
    print(f"wrote related-papers/index.html ({len(rows)} entries)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
